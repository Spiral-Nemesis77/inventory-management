<script>
import { ref, computed, watch, onMounted } from 'vue'
import { api } from '../api'
import { useFilters } from '../composables/useFilters'
import { useI18n } from '../composables/useI18n'
import { formatCurrency, formatCurrencyWithDecimals } from '../utils/currency'

const MONTH_KEYS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec']
const MAX_BAR_HEIGHT = 200

export default {
  name: 'Reports',
  setup() {
    const { t, currentCurrency } = useI18n()

    const loading = ref(true)
    const error = ref(null)
    const quarterlyData = ref([])
    const monthlyData = ref([])

    const {
      selectedPeriod,
      selectedLocation,
      selectedCategory,
      selectedStatus,
      getCurrentFilters
    } = useFilters()

    // Guards against an older, slower response overwriting a newer one when filters change quickly
    let requestId = 0

    const loadData = async () => {
      const currentRequest = ++requestId
      try {
        loading.value = true
        error.value = null
        const filters = getCurrentFilters()
        const [quarterly, monthly] = await Promise.all([
          api.getQuarterlyReport(filters),
          api.getMonthlyTrends(filters)
        ])
        if (currentRequest !== requestId) return
        quarterlyData.value = quarterly
        monthlyData.value = monthly
      } catch (err) {
        if (currentRequest !== requestId) return
        console.error('Failed to load reports:', err)
        error.value = t('reports.loadFailed') + ': ' + err.message
      } finally {
        if (currentRequest === requestId) loading.value = false
      }
    }

    watch([selectedPeriod, selectedLocation, selectedCategory, selectedStatus], () => {
      loadData()
    })

    const isEmpty = computed(() => quarterlyData.value.length === 0 && monthlyData.value.length === 0)

    // "YYYY-MM" strings sort chronologically; don't rely on the API ordering for the change calculation
    const sortedMonthly = computed(() =>
      [...monthlyData.value].sort((a, b) => a.month.localeCompare(b.month))
    )

    const totalRevenue = computed(() =>
      monthlyData.value.reduce((sum, m) => sum + m.revenue, 0)
    )

    const avgMonthlyRevenue = computed(() =>
      monthlyData.value.length > 0 ? totalRevenue.value / monthlyData.value.length : 0
    )

    const totalOrders = computed(() =>
      monthlyData.value.reduce((sum, m) => sum + m.order_count, 0)
    )

    const bestQuarter = computed(() => {
      let best = null
      for (const q of quarterlyData.value) {
        if (best === null || q.total_revenue > best.total_revenue) best = q
      }
      return best && best.total_revenue > 0 ? best.quarter : ''
    })

    const maxRevenue = computed(() =>
      monthlyData.value.reduce((max, m) => Math.max(max, m.revenue), 0)
    )

    const monthOverMonthRows = computed(() =>
      sortedMonthly.value.map((m, i) => {
        if (i === 0) return { ...m, change: null, growthRate: null }
        const prev = sortedMonthly.value[i - 1].revenue
        const change = m.revenue - prev
        // Growth against a zero base is undefined
        const growthRate = prev === 0 ? null : (change / prev) * 100
        return { ...m, change, growthRate }
      })
    )

    const getBarHeight = (revenue) => {
      if (maxRevenue.value === 0) return 0
      return (revenue / maxRevenue.value) * MAX_BAR_HEIGHT
    }

    const formatMonth = (monthStr) => {
      const [year, month] = String(monthStr).split('-')
      const key = MONTH_KEYS[parseInt(month, 10) - 1]
      if (!key) return monthStr
      return `${t('months.' + key)} ${year}`
    }

    const getFulfillmentClass = (rate) => {
      if (rate >= 90) return 'badge success'
      if (rate >= 75) return 'badge warning'
      return 'badge danger'
    }

    const getChangeClass = (change) => {
      if (change > 0) return 'positive-change'
      if (change < 0) return 'negative-change'
      return ''
    }

    // Sign is placed before the currency symbol (e.g. -$1,200.00), so format the absolute value
    const formatChange = (change) => {
      const sign = change > 0 ? '+' : change < 0 ? '-' : ''
      return sign + formatCurrencyWithDecimals(Math.abs(change), currentCurrency.value, 2)
    }

    const formatGrowthRate = (rate) => {
      if (rate === null) return t('reports.mom.notAvailable')
      const sign = rate > 0 ? '+' : ''
      return sign + rate.toFixed(1) + '%'
    }

    onMounted(() => {
      loadData()
    })

    return {
      t,
      currentCurrency,
      formatCurrency,
      formatCurrencyWithDecimals,
      loading,
      error,
      quarterlyData,
      sortedMonthly,
      isEmpty,
      totalRevenue,
      avgMonthlyRevenue,
      totalOrders,
      bestQuarter,
      monthOverMonthRows,
      getBarHeight,
      formatMonth,
      getFulfillmentClass,
      getChangeClass,
      formatChange,
      formatGrowthRate
    }
  }
}
</script>

